import { mapRuntime } from "../catalog.js";
import { ConfigError } from "../errors.js";
import type {
  EventConfig,
  EntryKind,
  FunctionConfig,
  KitConfig,
  PhysicalFunction,
  PlanResult,
  PlannedWorkflow,
  ProviderName,
} from "../types.js";
import { cloudName, tfIdent } from "../util/hash.js";

export function planDeployment(config: KitConfig): PlanResult {
  const warnings: string[] = [];
  const runtimeWarning = new Set<string>();
  const functions = injectInvokeRoutes(config);
  const physical: PhysicalFunction[] = [];

  for (const [logicalName, fn] of Object.entries(functions)) {
    const runtime = fn.runtime ?? config.provider.runtime;
    const mapped = mapRuntime(config.provider.name, runtime);
    if (mapped.warning && !runtimeWarning.has(mapped.warning)) {
      runtimeWarning.add(mapped.warning);
      warnings.push(mapped.warning);
    }
    const shared = {
      logicalName,
      handler: fn.handler,
      description: fn.description,
      runtime,
      providerRuntime: mapped.value,
      esbuildTarget: mapped.esbuildTarget,
      memory: fn.memory ?? config.provider.memory,
      timeout: fn.timeout ?? config.provider.timeout,
      environment: { ...config.provider.environment, ...fn.environment },
      architecture: fn.architecture ?? config.provider.architecture,
    };
    physical.push(...fanOut(config.provider.name, logicalName, fn.events, shared));
  }

  const workflows: PlannedWorkflow[] = Object.entries(config.workflows).map(([name, workflow]) => ({
    name,
    tfId: tfIdent("wf", name),
    config: workflow,
    engine: workflow.engine,
  }));

  const portable = workflows.filter((workflow) => workflow.engine === "portable");
  if (portable.length > 0) {
    const runtime = config.provider.runtime;
    const mapped = mapRuntime(config.provider.name, runtime);
    physical.push({
      logicalName: "__sk_workflow_runner",
      physicalName: cloudName([config.service, config.provider.stage, "workflow-runner"]),
      tfId: tfIdent("fn", "workflow_runner"),
      handler: "serverless-kit/runtime.workflow",
      description: "Portable workflow runner generated by serverless-kit",
      runtime,
      providerRuntime: mapped.value,
      esbuildTarget: mapped.esbuildTarget,
      memory: config.provider.memory,
      timeout: Math.max(config.provider.timeout, 60),
      environment: { ...config.provider.environment },
      architecture: config.provider.architecture,
      events: [
        {
          type: "http",
          http: {
            path: config.provider.name === "azure" ? "/sk/workflows/{name}" : "/__sk/workflows/{name}",
            method: "POST",
            auth: "provider",
            cors: false,
            internal: true,
          },
        },
      ],
      entry: runnerEntry(config.provider.name),
      azureBinding: config.provider.name === "azure" ? "http" : undefined,
    });
  }

  const ids = new Set<string>();
  for (const fn of physical) {
    if (ids.has(fn.tfId)) {
      throw new ConfigError(`Two functions produced the same Terraform id "${fn.tfId}". Rename a function.`);
    }
    ids.add(fn.tfId);
  }

  return {
    functions: physical,
    workflows,
    warnings,
    needsInvokeToken: functionsNeedToken(config) || portable.length > 0,
  };
}

function functionsNeedToken(config: KitConfig): boolean {
  return Object.values(config.workflows).some((workflow) => workflow.engine === "portable" || config.provider.name === "gcp");
}

interface SharedFields {
  logicalName: string;
  handler: string;
  description?: string;
  runtime: PhysicalFunction["runtime"];
  providerRuntime: string;
  esbuildTarget: string;
  memory: number;
  timeout: number;
  environment: Record<string, string>;
  architecture: "x86_64" | "arm64";
}

function fanOut(provider: ProviderName, logicalName: string, events: EventConfig[], shared: SharedFields): PhysicalFunction[] {
  if (provider === "gcp") return fanOutGcp(logicalName, events, shared);
  if (provider === "azure") return fanOutAzure(logicalName, events, shared);
  return [
    makePhysical(logicalName, logicalName, events, shared, entryFor(provider, events), undefined),
  ];
}

function fanOutGcp(logicalName: string, events: EventConfig[], shared: SharedFields): PhysicalFunction[] {
  const httpish = events.filter((event) => event.type === "http" || event.type === "schedule");
  const background = events.filter((event) => event.type !== "http" && event.type !== "schedule");
  const out: PhysicalFunction[] = [];
  if (httpish.length === 0 && background.length === 0) {
    out.push(makePhysical(logicalName, logicalName, [], shared, "gcp-http"));
  }
  if (httpish.length > 0) {
    out.push(makePhysical(logicalName, logicalName, httpish, shared, "gcp-http"));
  }
  if (background.length === 1) {
    const physicalName = httpish.length > 0 ? `${logicalName}-${background[0].type}` : logicalName;
    out.push(makePhysical(logicalName, physicalName, background, shared, "gcp-event"));
  }
  return out;
}

function fanOutAzure(logicalName: string, events: EventConfig[], shared: SharedFields): PhysicalFunction[] {
  if (events.length === 0) {
    return [
      makePhysical(
        logicalName,
        logicalName,
        [
          {
            type: "http",
            http: { path: `/invoke/${logicalName}`, method: "POST", auth: "provider", cors: false },
          },
        ],
        shared,
        "azure",
        "http",
      ),
    ];
  }
  return events.map((event, index) => {
    const suffix = events.length === 1 ? logicalName : `${logicalName}-${event.type}-${index + 1}`;
    return makePhysical(logicalName, suffix, [event], shared, "azure", azureBinding(event));
  });
}

function makePhysical(
  logicalName: string,
  physicalName: string,
  events: EventConfig[],
  shared: SharedFields,
  entry: EntryKind,
  azureBinding?: PhysicalFunction["azureBinding"],
): PhysicalFunction {
  return {
    ...shared,
    logicalName,
    physicalName,
    tfId: tfIdent("fn", physicalName),
    events,
    entry,
    azureBinding,
  };
}

function entryFor(provider: ProviderName, events: EventConfig[]): EntryKind {
  switch (provider) {
    case "gcp":
      return events.some((event) => event.type !== "http" && event.type !== "schedule") ? "gcp-event" : "gcp-http";
    case "azure":
      return "azure";
    case "cloudflare":
      return "cloudflare";
    case "ibm":
    case "digitalocean":
      return "openwhisk";
    case "oracle":
      return "oracle";
    default:
      return "lambda";
  }
}

function runnerEntry(provider: ProviderName): EntryKind {
  if (provider === "gcp") return "gcp-http";
  if (provider === "azure") return "azure";
  if (provider === "cloudflare") return "cloudflare";
  if (provider === "ibm" || provider === "digitalocean") return "openwhisk";
  if (provider === "oracle") return "oracle";
  return "lambda";
}

function azureBinding(event: EventConfig): PhysicalFunction["azureBinding"] {
  switch (event.type) {
    case "schedule":
      return "timer";
    case "queue":
      return "queue";
    case "topic":
      return "serviceBus";
    case "storage":
      return "blob";
    default:
      return "http";
  }
}

/**
 * Copy functions and add the internal HTTP route workflow calls need.
 * Native AWS Step Functions invoke Lambda directly, so they do not get this route.
 */
function injectInvokeRoutes(config: KitConfig): Record<string, FunctionConfig> {
  const targets = new Set<string>();
  for (const workflow of Object.values(config.workflows)) {
    const usesHttp = workflow.engine === "portable" || config.provider.name === "gcp";
    if (!usesHttp) continue;
    for (const state of Object.values(workflow.states)) {
      if (state.type === "task") targets.add(state.function);
    }
  }
  const out: Record<string, FunctionConfig> = {};
  for (const [name, fn] of Object.entries(config.functions)) {
    if (!targets.has(name)) {
      out[name] = fn;
      continue;
    }
    if (config.provider.name === "gcp") {
      const backgroundOnly =
        fn.events.length > 0 && fn.events.every((event) => event.type !== "http" && event.type !== "schedule");
      if (backgroundOnly) {
        throw new ConfigError(
          `Workflows call "${name}" over HTTP. On Google Cloud that function only has a background trigger. Add an http event, or move the workflow task to an HTTP function.`,
        );
      }
    }
    const path = config.provider.name === "azure" ? `/sk/invoke/${name}` : `/__sk/invoke/${name}`;
    const internal: EventConfig = {
      type: "http",
      http: { path, method: "POST", auth: "provider", cors: false, internal: true },
    };
    out[name] = { ...fn, events: [...fn.events, internal] };
  }
  return out;
}
