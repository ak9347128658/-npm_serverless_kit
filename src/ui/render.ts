import type { DeploymentModel } from "../types.js";

export function renderDashboard(model: DeploymentModel): string {
  const data = JSON.stringify(model).replace(/</g, "\\u003c");
  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>${escapeHtml(model.title)}</title>
<style>
  :root { color-scheme: dark; --bg:#0e1412; --card:#17211e; --line:#2a3b36; --text:#e7f2ee; --muted:#93a8a1; --accent:#3dd6c6; --warn:#e6b35a; }
  * { box-sizing: border-box; }
  body { margin:0; font:16px/1.5 ui-sans-serif, system-ui, sans-serif; background:var(--bg); color:var(--text); }
  header, main { width:min(1100px, calc(100% - 32px)); margin:0 auto; }
  header { padding:32px 0 8px; }
  h1 { font-size:28px; margin:0 0 8px; letter-spacing:-0.03em; }
  .meta { color:var(--muted); display:flex; flex-wrap:wrap; gap:10px 16px; }
  .badge { border:1px solid var(--line); border-radius:999px; padding:2px 10px; color:var(--accent); }
  .banner { background:#3a2e16; color:#f3ddb0; padding:12px 14px; border-radius:10px; margin:18px 0; }
  .stats { display:grid; grid-template-columns:repeat(4, 1fr); gap:12px; margin:18px 0; }
  .stat, article { background:var(--card); border:1px solid var(--line); border-radius:14px; }
  .stat { padding:14px 16px; }
  .stat b { display:block; font-size:22px; }
  .stat span, .muted { color:var(--muted); }
  input { width:100%; padding:12px 14px; border-radius:10px; border:1px solid var(--line); background:#0e1412; color:var(--text); }
  article { padding:16px 18px; margin:12px 0; }
  article h2 { margin:0 0 6px; font-size:18px; }
  .row { display:flex; flex-wrap:wrap; gap:8px 14px; color:var(--muted); font-size:14px; }
  code, .id { font-family:ui-monospace, SFMono-Regular, Menlo, Consolas, monospace; font-size:13px; }
  button { background:transparent; color:var(--accent); border:1px solid var(--line); border-radius:8px; padding:2px 8px; cursor:pointer; }
  ul { margin:8px 0 0; padding-left:18px; }
  .warn { color:var(--warn); }
  footer { color:var(--muted); padding:24px 0 40px; font-size:13px; }
  @media (max-width: 800px) { .stats { grid-template-columns:1fr 1fr; } }
</style>
</head>
<body>
<header>
  <h1 id="title"></h1>
  <div class="meta" id="meta"></div>
</header>
<main>
  <div id="banner"></div>
  <section class="stats" id="stats"></section>
  <input id="q" placeholder="Filter functions, triggers, handlers, ARNs" aria-label="Filter" />
  <section id="functions"></section>
  <section id="workflows"></section>
  <footer>Generated by serverless-kit. Environment values stay in Terraform state and are not shown here. Only the variable names are listed.</footer>
</main>
<script id="data" type="application/json">${data}</script>
<script>
const model = JSON.parse(document.getElementById("data").textContent);
const title = document.getElementById("title");
title.textContent = model.title;
document.getElementById("meta").innerHTML = [
  badge(model.providerTitle),
  badge(model.region),
  badge("stage " + model.stage),
  badge(model.runtime),
  badge(model.status)
].join("");
const banner = document.getElementById("banner");
if (model.status !== "deployed") {
  banner.innerHTML = '<div class="banner">This page is a preview of the configuration. Run <b>sk deploy</b> to fill ARNs, ids, and URLs.</div>';
} else {
  banner.innerHTML = '<div class="row">Deployed ' + escapeHtml(model.deployedAt || "") + "</div>";
}
const warnings = (model.warnings || []).map((item) => '<div class="warn">' + escapeHtml(item) + "</div>").join("");
if (warnings) banner.innerHTML += warnings;
const publicTriggers = model.functions.reduce((sum, fn) => sum + fn.triggers.filter((t) => !t.internal).length, 0);
document.getElementById("stats").innerHTML = [
  stat(model.functions.length, "Functions"),
  stat(publicTriggers, "Triggers"),
  stat(model.workflows.length, "Workflows"),
  stat(model.provider, "Provider")
].join("");
const query = document.getElementById("q");
function draw() {
  const needle = query.value.trim().toLowerCase();
  document.getElementById("functions").innerHTML = model.functions.filter((fn) => JSON.stringify(fn).toLowerCase().includes(needle)).map(renderFunction).join("") || "<p class='muted'>No functions match.</p>";
  document.getElementById("workflows").innerHTML = model.workflows.filter((wf) => JSON.stringify(wf).toLowerCase().includes(needle)).map(renderWorkflow).join("");
}
query.addEventListener("input", draw);
draw();
document.body.addEventListener("click", (event) => {
  const button = event.target.closest("button[data-copy]");
  if (!button) return;
  const value = button.getAttribute("data-copy");
  navigator.clipboard.writeText(value).then(() => { button.textContent = "Copied"; setTimeout(() => { button.textContent = "Copy"; }, 1200); }).catch(() => { button.textContent = "Select the value"; });
});
function renderFunction(fn) {
  const ids = ["url", "arn", "id"].filter((key) => fn[key]).map((key) => '<div class="row"><span>' + key + '</span> <span class="id">' + escapeHtml(fn[key]) + '</span> <button data-copy="' + escapeAttr(fn[key]) + '">Copy</button></div>').join("");
  const triggers = fn.triggers.map((trigger) => "<li>" + escapeHtml(trigger.type) + (trigger.internal ? " (internal)" : "") + " — " + escapeHtml(trigger.detail || "") + "</li>").join("");
  return '<article><h2>' + escapeHtml(fn.logicalName) + '</h2><div class="row"><span>' + escapeHtml(fn.handler) + '</span><span>' + escapeHtml(fn.providerRuntime) + '</span><span>' + fn.memory + ' MB</span><span>' + fn.timeout + 's</span><span>' + escapeHtml(fn.entry) + '</span></div>' + (fn.description ? '<p>' + escapeHtml(fn.description) + '</p>' : '') + ids + '<ul>' + triggers + '</ul>' + (fn.environmentKeys.length ? '<p class="muted">Env keys: ' + escapeHtml(fn.environmentKeys.join(", ")) + '</p>' : '') + '</article>';
}
function renderWorkflow(wf) {
  return '<article><h2>Workflow ' + escapeHtml(wf.name) + '</h2><div class="row"><span>' + escapeHtml(wf.engine) + '</span><span>' + escapeHtml(wf.type) + '</span><span>start ' + escapeHtml(wf.startAt) + '</span></div>' + (wf.arn ? '<div class="id">' + escapeHtml(wf.arn) + '</div>' : '') + (wf.comment ? '<p>' + escapeHtml(wf.comment) + '</p>' : '') + '</article>';
}
function stat(value, label) { return '<div class="stat"><b>' + escapeHtml(String(value)) + '</b><span>' + escapeHtml(label) + '</span></div>'; }
function badge(value) { return '<span class="badge">' + escapeHtml(value) + '</span>'; }
function escapeHtml(value) { return String(value).replace(/[&<>"']/g, (ch) => ({ "&":"&amp;", "<":"&lt;", ">":"&gt;", '"':"&quot;", "'":"&#39;" }[ch])); }
function escapeAttr(value) { return escapeHtml(value).replace(/"/g, "&quot;"); }
</script>
</body>
</html>
`;
}

export function dashboardPathNote(model: DeploymentModel): string {
  return `${model.functions.length} function(s) on ${model.providerTitle}`;
}

function escapeHtml(value: string): string {
  return value.replace(/[&<>"']/g, (char) => {
    const map: Record<string, string> = { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" };
    return map[char] ?? char;
  });
}
